import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getBuildVersion } from './build-version.mjs';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));
const outputDirectory = path.join(projectRoot, 'dist', 'public');
const basePath = normaliseBasePath(process.env.BASE_PATH ?? '/');
const buildVersion = getBuildVersion();

function listFiles(directory, prefix = '') {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const relativePath = path.posix.join(prefix, entry.name);
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) return listFiles(absolutePath, relativePath);
    if (relativePath === 'sw.js') return [];
    return [relativePath];
  });
}

function normaliseBasePath(value) {
  const pathWithLeadingSlash = value.startsWith('/') ? value : `/${value}`;
  return pathWithLeadingSlash.endsWith('/')
    ? pathWithLeadingSlash
    : `${pathWithLeadingSlash}/`;
}

const precacheUrls = [
  basePath,
  ...listFiles(outputDirectory).map((file) => `${basePath}${file}`),
];

const worker = `/* Generated by scripts/generate-service-worker.mjs. */
const APP_CACHE = ${JSON.stringify(`window-quotes-app-${buildVersion}`)};
const FONT_CACHE = 'window-quotes-fonts-v1';
const BASE_PATH = ${JSON.stringify(basePath)};
const PRECACHE_URLS = ${JSON.stringify([...new Set(precacheUrls)])};
const FONT_HOSTS = new Set(['fonts.googleapis.com', 'fonts.gstatic.com']);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(APP_CACHE).then((cache) => cache.addAll(PRECACHE_URLS)),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys
          .filter((key) => key.startsWith('window-quotes-') && key !== APP_CACHE && key !== FONT_CACHE)
          .map((key) => caches.delete(key)),
      ))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});

async function fontResponse(request) {
  const cache = await caches.open(FONT_CACHE);
  try {
    const response = await fetch(request);
    if (response.ok) {
      try {
        await cache.put(request, response.clone());
      } catch {
        // A browser may refuse a cross-origin font response; online use still works.
      }
    }
    return response;
  } catch {
    return (await cache.match(request)) || new Response('', { status: 504 });
  }
}

async function appNavigationResponse(request) {
  try {
    const response = await fetch(request);
    if (response.ok) return response;
  } catch {
    // Serve the cached app shell below when the device is offline.
  }
  const cache = await caches.open(APP_CACHE);
  return (await cache.match(BASE_PATH)) || (await cache.match(BASE_PATH + 'index.html'));
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (FONT_HOSTS.has(url.hostname)) {
    event.respondWith(fontResponse(request));
    return;
  }

  if (url.origin !== self.location.origin) return;

  const scopePath = new URL(BASE_PATH, self.location.origin).pathname;
  if (request.mode === 'navigate' && url.pathname.startsWith(scopePath)) {
    event.respondWith(appNavigationResponse(request));
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request)),
  );
});
`;

writeFileSync(path.join(outputDirectory, 'sw.js'), worker);
console.log(`Generated service worker for ${basePath} (${buildVersion}).`);
